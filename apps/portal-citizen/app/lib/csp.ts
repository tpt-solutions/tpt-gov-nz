/**
 * Content-Security-Policy for the portal. Middleware generates a fresh nonce for
 * every request and applies this policy, so inline scripts need the nonce and
 * `unsafe-inline` is not allowed for scripts.
 *
 * Styles still allow `unsafe-inline` because components use React `style` props.
 * Moving those to classes is tracked in TODO.md ("reduce inline styles").
 */
export function buildCsp(nonce: string, isDev: boolean): string {
  return [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}'${isDev ? " 'unsafe-eval'" : ""}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self' data:",
    "connect-src 'self'",
    "manifest-src 'self'",
    "worker-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join("; ");
}

/** A base64 nonce from Web Crypto. Works in the Edge runtime. */
export function generateNonce(): string {
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  let binary = "";
  for (const b of bytes) binary += String.fromCharCode(b);
  return btoa(binary);
}
